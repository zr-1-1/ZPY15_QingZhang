function [E_t] = OE_scl_ptb(E_0, t)
% 计算轨道根数随时间的变化，考虑J2摄动对平均摄动影响，输入E_0为初始轨道根数和递推时间t，输出为最终轨道根数E_t
% 该函数计算与赛题要求一致
% E_0/E_t：[a(m), e, i(rad), Omega(rad), omega(rad), M(rad)]；t 为 s。
% 全局参数：J_2 无量纲，R_E 为 m，mu 为 m^3/s^2，调用前须初始化。
% 输出角度保留累计弧度，不折回 [0, 2*pi)。
    % 导入全局变量，保持参数一致性
    global J_2 R_E mu
    
    a0 = E_0(1); e0 = E_0(2); i0 = E_0(3); Omega0 = E_0(4); omega0 = E_0(5); M0 = E_0(6);
    n = sqrt(mu/a0^3); % 平均运动，单位 rad/s
    C_J2 = 1.5*J_2*(R_E/a0)^2*n; % R_E/a0 无量纲，系数单位 rad/s
    
    Omega_t = Omega0 - C_J2*cos(i0)/(1-e0^2)^2*t; % 近似计算升交点赤经变化后值，适用于长期变化计算，但该值对于短期变化来说并不准确，升交点赤经并不是线性的
    % 注意，该公式是把J2引起的近地点角距的周期性摄动平均化看待，然后线性计算升交点赤经的变化量，以此来近似得到升交点赤经
    omega_t = omega0 + C_J2*(2-2.5*sin(i0)^2)/(1-e0^2)^2*t; % 近似计算近地点角距变化后值，适用于长期变化计算，但该值对于短期变化来说并不准确，近地点角距并不是线性的
    % 平均运动与 J2 摄动速率均为 rad/s，相加后乘以时间得到弧度变化量
    M_dot = n + 0.5*C_J2*(1-e0^2)^(-1.5)*(3*cos(i0)^2-1);
    M_t = M0 + M_dot*t; % 平近点角，单位 rad
    E_t = [a0, e0, i0, Omega_t, omega_t, M_t];
end
